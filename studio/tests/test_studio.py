from playwright.sync_api import sync_playwright
from pathlib import Path
import os, shutil, sys
import json, traceback, re
ROOT=Path(__file__).resolve().parents[1]
ARTIFACTS=ROOT/'tests'/'_artifacts'
ARTIFACTS.mkdir(parents=True, exist_ok=True)
results=[]
def check(name, fn):
    try:
        ok=fn()
        if ok is False:raise AssertionError(name)
        results.append((name,'PASS',str(ok)[:160]));print('PASS',name,flush=True)
    except Exception as exc:
        results.append((name,'FAIL',repr(exc)));print('FAILED',name,repr(exc))
with sync_playwright() as p:
 browser=p.chromium.launch(executable_path=os.environ.get('SVARA_CHROMIUM') or shutil.which('chromium') or shutil.which('google-chrome') or None,headless=True,args=['--no-sandbox','--autoplay-policy=no-user-gesture-required','--disable-web-security'])
 for dim in [(1440,900),(390,844),(360,750)]:
    ctx=browser.new_context(viewport={'width':dim[0],'height':dim[1]},accept_downloads=True)
    page=ctx.new_page();page.set_default_timeout(4000);errors=[];page.on('pageerror', lambda e:errors.append(str(e)))
    page.set_content((ROOT/'index.html').read_text(),wait_until='domcontentloaded',timeout=8000);page.wait_for_timeout(160)
    prefix=f'{dim[0]}x{dim[1]}'
    check(prefix+' initial no JS errors',lambda: not errors or errors)
    check(prefix+' 72 melakarta',lambda:page.evaluate('MELAKARTA.length')==72)
    check(prefix+' choose compose',lambda: page.locator('[data-view="compose"]').click() or page.locator('#view-compose').evaluate('(e)=>e.classList.contains("active")'))
    check(prefix+' 7 slots',lambda:page.locator('.compose-slot').count()==7)
    check(prefix+' initial phrase',lambda:page.locator('#composerInput').input_value()=='NAMASTE')
    check(prefix+' no horizontal overflow',lambda:page.evaluate('document.documentElement.scrollWidth<=window.innerWidth+2') or page.evaluate('[document.documentElement.scrollWidth,window.innerWidth]'))
    check(prefix+' phrase change',lambda:page.locator('#composerInput').fill('ABCDEFG') or page.evaluate('composerUnits().length')==7)
    check(prefix+' C tonic pitch map 7 slots',lambda:page.evaluate('composerGetEvents().every(e=>Number.isFinite(e.midi))'))
    page.locator('#tonic').select_option('2')
    check(prefix+' change Sa updates pitch',lambda:page.evaluate('composerGetEvents()[0].midi')==61 if page.evaluate('state.raga.id')=='yaman' else page.evaluate('composerGetEvents()[0].midi') is not None)
    page.locator('#composerRaga').select_option('bhoopali')
    check(prefix+' Bhoopali path always legal',lambda:page.evaluate('composerGetEvents().every(e=>e.midi===null||[0,2,4,7,9,12].includes(e.midi-tonicMidi()))'))
    page.locator('#composerMapping').select_option('degree')
    check(prefix+' Bhoopali degree rest for missing Ma',lambda:page.evaluate('composerGetEvents().filter(e=>e.midi===null).length')>=2)
    page.locator('#composerMapping').select_option('path')
    check(prefix+' no rest using safe path',lambda:page.evaluate('composerGetEvents().every(e=>e.midi!==null)'))
    page.locator('#composerInput').fill('NAMASTE')
    page.locator('#composerTempo').evaluate('(e)=>{e.value=142;e.dispatchEvent(new Event("input",{bubbles:true}))}')
    check(prefix+' tempo updates',lambda:page.locator('#composerTempoLabel').inner_text()=='142')
    page.locator('#composerHear').click();page.wait_for_timeout(220)
    check(prefix+' play started',lambda:page.evaluate('comp.playing'))
    page.locator('#composerStop').click();page.wait_for_timeout(80)
    check(prefix+' stop cancels composer',lambda:page.evaluate('!comp.playing&&comp.timer===null&&comp.voices.size===0'))
    page.locator('#composerLoop').click();page.wait_for_timeout(130)
    check(prefix+' loop starts',lambda:page.evaluate('comp.playing&&comp.loop'))
    page.locator('#composerLoop').click();page.wait_for_timeout(80)
    check(prefix+' loop stopped',lambda:page.evaluate('!comp.playing'))
    page.locator('#composerTala').check();page.locator('#composerTempo').evaluate('(e)=>{e.value=96;e.dispatchEvent(new Event("input",{bubbles:true}))}');page.locator('#composerHear').click();page.wait_for_timeout(260)
    check(prefix+' tabla aligned and active',lambda:page.evaluate('comp.playing&&state.rhythm&&comp.ownsRhythm'))
    page.evaluate('stopPlayback()');page.wait_for_timeout(80)
    check(prefix+' cross stop cancels composer and percussion',lambda:page.evaluate('!comp.playing&&!state.rhythm&&percussionVoices.size===0'))
    page.locator('#composerTala').uncheck()
    with page.expect_download() as info:page.locator('#composerMidi').click()
    d=info.value;check(prefix+' MIDI exported',lambda:d.suggested_filename.endswith('.mid'))
    d.save_as(str(ARTIFACTS/'svara_test.mid'))
    with page.expect_download() as info:page.locator('#composerExport').click()
    check(prefix+' JSON exported',lambda:info.value.suggested_filename.endswith('.json'))
    page.locator('#composerSave').click()
    check(prefix+' local notebook saved',lambda:page.locator('.compose-save-row').count()>=1)
    page.locator('#composerClear').click()
    check(prefix+' phrase cleared',lambda:page.locator('#composerInput').input_value()=='')
    page.locator('.compose-save-row button').first.click()
    check(prefix+' notebook load',lambda:page.locator('#composerInput').input_value()=='NAMASTE')
    page.locator('#composerInput').fill('क')
    page.locator('#composerInputMode').select_option('akshara')
    page.locator('#composerInput').focus()
    page.locator('#composerInput').evaluate('(e)=>e.setSelectionRange(e.value.length,e.value.length)')
    page.evaluate("composerInsert('आ','vowel')")
    check(prefix+' vowel matra attached',lambda:page.locator('#composerInput').input_value()=='का')
    page.locator('#composerInput').fill('क');page.locator('#composerInput').evaluate('(e)=>e.setSelectionRange(e.value.length,e.value.length)');page.evaluate("composerInsert('्','join');composerInsert('ष','consonant')")
    check(prefix+' Devanagari conjunct grouped as grapheme',lambda:page.evaluate('composerUnits().length')==1)
    check(prefix+' no JS errors after actions',lambda: not errors or errors)
    page.locator('#composerInputMode').select_option('sargam')
    page.locator('#composerInput').fill('S R g M+ P d N')
    check(prefix+' direct sargam tokens',lambda:page.evaluate('composerGetEvents().map(e=>e.token).join(" " )')=='S R g M+ P d N')
    page.locator('#composerInput').fill('S X R')
    check(prefix+' invalid sargam is silent not Sa',lambda:page.evaluate('composerGetEvents()[1].midi===null'))
    page.locator('#composerInputMode').select_option('akshara')
    page.locator('#composerInput').fill('का')
    page.locator('#composerInput').evaluate('(e)=>e.setSelectionRange(e.value.length,e.value.length)')
    page.evaluate("composerInsert('्','join')")
    check(prefix+' invalid join after matra refused',lambda:page.locator('#composerInput').input_value()=='का')
    if dim[0]==1440:page.screenshot(path=str(ARTIFACTS/'desktop.png'),full_page=True)
    if dim[0]==390:page.screenshot(path=str(ARTIFACTS/'mobile.png'),full_page=True)
    ctx.close()
 browser.close()
print('\n'.join(f'{n}: {v} {i}' for n,v,i in results))
print('RESULTS',sum(x[1]=='PASS' for x in results),'/',len(results))
(ARTIFACTS/'results.json').write_text(json.dumps(results,ensure_ascii=False,indent=2))

if any(status=='FAIL' for _,status,_ in results): sys.exit(1)